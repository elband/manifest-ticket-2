/**
 * Tombol Demo Scan di kiosk aktif? NEXT_PUBLIC_ENABLE_DEMO_SCAN="true"/"false"
 * memaksa nyala/mati; bila tidak diset: nyala di dev, MATI di build produksi.
 * (Diakses literal agar Next meng-inline nilainya di bundle klien.)
 */
export function demoScanEnabled(): boolean {
  const flag = process.env.NEXT_PUBLIC_ENABLE_DEMO_SCAN;
  if (flag === "true") return true;
  if (flag === "false") return false;
  return process.env.NODE_ENV !== "production";
}

/** Tanggal efektif boarding pass: pakai departureDate bila ada, else dari dateRef. */
function resolveBpDate(bp: SeedBoardingPass): string {
  if (bp.departureDate) return bp.departureDate;
  return bp.dateRef === "tomorrow" ? tomorrowDateString() : todayDateString();
}

export function buildPayload(bp: SeedBoardingPass): string {
  const safeName = bp.passengerName.replace(/\|/g, " ").toUpperCase();
  // Field ke-6 = tanggal keberangkatan → validator bisa menolak boarding pass
  // yang tanggalnya sudah lewat (bukan hari ini).
  return `${bp.flightNumber}|${bp.pnr}|${bp.ticket}|${bp.seat}|${safeName}|${resolveBpDate(bp)}`;
}

/**
 * Pastikan flight untuk boarding pass demo ADA di storage & sedang boarding
 * (jadwal HARI INI, status ACTIVE, STD ≈ sekarang) supaya Demo Scan menghasilkan
 * VALID — bukan UNKNOWN_FLIGHT saat belum ada jadwal di-seed.
 * Upsert by flightNumber + tanggal hari ini. Dipakai khusus mode demo/kiosk.
 */
export function ensureDemoBoardingFlight(bp: SeedBoardingPass): void {
  const today = todayDateString();
  const now = new Date();
  const hhmm = `${String(now.getHours()).padStart(2, "0")}:${String(
    now.getMinutes(),
  ).padStart(2, "0")}`;
  const existing = getFlights().find(
    (f) =>
      f.flightNumber.toUpperCase() === bp.flightNumber.toUpperCase() &&
      f.departureDate === today,
  );
  if (existing) {
    // Jamin boardable: STD ≈ sekarang + status ACTIVE (final call).
    updateFlight(existing.id, { status: "ACTIVE", departureTime: hhmm });
    return;
  }
  const iso = now.toISOString();
  const flight: Flight = {
    id: uid("flt"),
    flightNumber: bp.flightNumber,
    airlineCode: bp.airlineCode,
    originAirport: bp.origin,
    destinationAirport: bp.destination,
    departureDate: today,
    departureTime: hhmm,
    gateOrCheckpoint: bp.gate,
    status: "ACTIVE",
    expectedPax: 80,
    createdAt: iso,
    updatedAt: iso,
  };
  addFlight(flight);
}
